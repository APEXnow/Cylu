int CMainFrame::OnCreate(LPCREATESTRUCT lpCreateStruct) 
{
	if (CFrameWnd::OnCreate(lpCreateStruct) == -1)
		return -1;

	CRect rcClientArea( 0,0,640,480 );
	MoveWindow( &rcClientArea, TRUE );

	SetWindowText( APP_TITLE );
	
	return 0;
}
