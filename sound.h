/*
	Sound effects, using the Allegro 5 audio add-on.

	The effects are WAV files in data/sounds, generated by
	tools/make_sounds.py.  A missing file just means that effect is silent.
*/

#ifndef _SOUND_H_
#define _SOUND_H_

enum SoundEffect
{
	SND_STEP,				//	Droid moves one square
	SND_BUMP,				//	Droid walks into something
	SND_PICKUP,				//	Object into a pocket
	SND_DROP,				//	Object put down
	SND_DEPOSIT,			//	Object deposited in the base computer
	SND_FORCEFIELD_OFF,		//	CPU chip disables a forcefield
	SND_TELEPORT,			//	Teleport key, or return to base
	SND_REFUEL,				//	Fuel cell or refuel at base
	SND_FUEL_LOW,			//	Fuel running low
	SND_MENU_MOVE,			//	Menu cursor, pocket select
	SND_MENU_SELECT,		//	Menu choice, next page
	SND_WHOOSH,				//	Bouncy text flying in
	SND_GAME_OVER,			//	Out of fuel
	SND_WIN,				//	All objects deposited

	SND_COUNT
};

//	Install audio and load the effects.  Returns false (with szError set)
//	if there's no audio device; the game then carries on silently.
bool SoundInit( char *szError, int nErrorSize );
void SoundShutdown( void );

void SoundPlay( int nEffect );

//	M key during play
void SoundToggleMute( void );
bool SoundMuted( void );

#endif
